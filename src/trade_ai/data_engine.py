def run_ai_prediction_inference(df: pd.DataFrame, sequence_length=5):
    """Ingests data frames, extracts the most recent candle sequence, and calculates tomorrow's direction."""
    if len(df) < (sequence_length + 14):  # Account for RSI warmup window
        return "Insufficient Data History", 0.0

    # 1. Filter out the final sequence block of features
    # Drop rows containing NaN values generated by indicator start-ups
    clean_df = df.dropna(subset=["Close", "EMA_9", "RSI_14"]).copy()

    if len(clean_df) < sequence_length:
        return "Warmup Active", 0.0

    target_slice = clean_df.tail(sequence_length)

    # 2. Extract clean raw float arrays
    features_matrix = target_slice[["Close", "EMA_9", "RSI_14"]].values

    # 3. Transform arrays into standard PyTorch Float Tensors matching input layout rules
    input_tensor = torch.tensor(features_matrix, dtype=torch.float32).unsqueeze(
        0
    )  # Shape: [1, 5, 3]

    with torch.no_grad():
        # Pass tensors straight into your custom neural layers
        raw_output_probability = prediction_ai(input_tensor).item()

    # 4. Convert structural probabilities into strict actionable trading tags
    if raw_output_probability >= 0.50:
        signal = "📈 BULLISH FORECAST (Buy/Long Signal)"
    else:
        signal = "📉 BEARISH FORECAST (Sell/Short Signal)"

    return signal, round(raw_output_probability * 100, 2)


def fetch_and_clean_candles(ticker: str, days_back: int, interval: str, exchange: str):
    """Queries your public OpenAlgo domain, standardizes columns, appends indicators, and calls your prediction AI."""
    end_date = datetime.date(2026, 10, 20)
    start_date = end_date - datetime.timedelta(days=int(days_back))
    start_str = start_date.strftime("%Y-%m-%d")
    end_str = end_date.strftime("%Y-%m-%d")

    try:
        print(
            f"[SDK Call] Requesting {exchange}:{ticker} ({interval}) via Data Engine..."
        )
        df = client.history(
            symbol=ticker,
            exchange=exchange,
            interval=interval,
            start_date=start_str,
            end_date=end_str,
            source="api",
        )

        if not isinstance(df, pd.DataFrame) or df.empty:
            return None, "API Empty Payload Error", 0.0

        df = df.copy()
        if df.index.name == "timestamp" or "timestamp" not in df.columns:
            df = df.reset_index()

        clean_cols = {}
        for col in df.columns:
            c_low = str(col).lower()
            if c_low in ["timestamp", "open", "high", "low", "close", "volume"]:
                clean_cols[col] = c_low.capitalize()
            else:
                clean_cols[col] = str(col)
        df = df.rename(columns=clean_cols)
        df = df.sort_values(by="Timestamp").reset_index(drop=True)

        MAX_ALLOWED_ROWS = 5000
        if len(df) > MAX_ALLOWED_ROWS:
            df = df.tail(MAX_ALLOWED_ROWS).reset_index(drop=True)

        # Run scratch indicator calculations layers
        df["EMA_9"] = calculate_ema(df, period=9)
        df["RSI_14"] = calculate_rsi(df, period=14)

        # Round values for display clarity
        numeric_targets = ["Open", "High", "Low", "Close", "EMA_9", "RSI_14"]
        for col in numeric_targets:
            if col in df.columns:
                df[col] = pd.to_numeric(df[col], errors="coerce").round(2)

        # Execute our forward pass AI prediction layer
        ai_signal, confidence = run_ai_prediction_inference(df, sequence_length=5)

        display_layout = [
            col
            for col in [
                "Timestamp",
                "Open",
                "High",
                "Low",
                "Close",
                "EMA_9",
                "RSI_14",
                "Volume",
            ]
            if col in df.columns
        ]

        return df[display_layout], ai_signal, confidence

    except Exception as e:
        print(f"[Data Engine Exception]: {e}")
        return None, f"Execution Failure: {e!s}", 0.0


def get_openalgo_status_message():
    """Queries the OpenAlgo server for the live analyzer status."""
    try:
        res = client.analyzerstatus()  # OpenAlgo endpoint for analyzer status
        if res.get("status") == "success":
            data = res.get("data", {})
            if not isinstance(data, dict):
                data = {}
            mode = data.get("mode", "unknown")
            analyze_mode = data.get("analyze_mode", True)
            return f"🟢 **OpenAlgo Status: Online** | Mode: `{mode}` | Sandbox Analyze Mode: `{analyze_mode}`"
        return "⚠️ OpenAlgo responded, but status check was unsuccessful."
    except Exception as e:
        return f"❌ **OpenAlgo Connection Error:** {e!s}"
